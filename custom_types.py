# ============================================================
# 1. IMPORT PYDANTIC
# ============================================================

import pydantic

# Pydantic provides data models for validating and structuring
# the data passed between different parts of the application.


# ============================================================
# 2. PDF CHUNKS AND SOURCE INFORMATION
# ============================================================

class RAGChunkAndSrc(pydantic.BaseModel):
    # Stores the text chunks extracted from a PDF document.
    # Each string represents a small section of the document.
    chunks: list[str]

    # Identifies the original PDF or document source.
    # Defaults to None if no source ID is provided.
    source_id: str = None


# ============================================================
# 3. PDF INGESTION RESULT
# ============================================================

class RAGUpsertResult(pydantic.BaseModel):
    # Stores the number of text chunks submitted to Qdrant.
    # This value indicates how many chunks were ingested.
    ingested: int


# ============================================================
# 4. VECTOR SEARCH RESULT
# ============================================================

class RAGSearchResult(pydantic.BaseModel):
    # Contains text chunks retrieved from Qdrant
    # because they are relevant to the user's question.
    contexts: list[str]

    # Contains source identifiers associated with the retrieved
    # chunks, helping the application identify document origins.
    sources: list[str]


# ============================================================
# 5. QUESTION-ANSWERING RESULT
# ============================================================

class RAQQueryResult(pydantic.BaseModel):
    # Stores the final answer generated by the language model.
    answer: str

    # Stores the source identifiers related to the answer.
    # Note: This field is singular "source", but its value is a list.
    source: list[str]

    # Records how many retrieved context chunks were used
    # to prepare the answer.
    num_contexts: int